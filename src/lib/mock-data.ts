function generateSeats(): Seat[] {
  const allSeats: Seat[] = [];
  const zones: Array<"A" | "B" | "C" | "D"> = ["A", "B", "C", "D"];

  const centerConfigs: Array<{
    centerId: string;
    seatsPerFloor: number;
    floors: number;
  }> = [
    { centerId: "ctr-001", seatsPerFloor: 20, floors: 3 },
    { centerId: "ctr-002", seatsPerFloor: 20, floors: 2 },
    { centerId: "ctr-003", seatsPerFloor: 15, floors: 2 },
    { centerId: "ctr-004", seatsPerFloor: 20, floors: 2 },
  ];

  const occupiedMap: Record<string, string> = {
    "ctr-001-A-12": "Priya Sharma",
    "ctr-001-B-05": "Rahul Verma",
    "ctr-001-D-01": "Sneha Patel",
    "ctr-001-A-18": "Rohan Gupta",
    "ctr-001-B-14": "Sanjay Kulkarni",
    "ctr-001-C-12": "Gaurav Sinha",
    "ctr-001-D-08": "Suresh Hegde",
    "ctr-001-A-20": "Divya Raghavan",
    "ctr-002-A-03": "Ananya Reddy",
    "ctr-002-C-08": "Vikram Joshi",
    "ctr-002-D-06": "Deepa Iyer",
    "ctr-002-A-09": "Nisha Agarwal",
    "ctr-002-B-07": "Tanvi Deshmukh",
    "ctr-002-C-10": "Manish Tiwari",
    "ctr-003-A-07": "Arjun Nair",
    "ctr-003-B-02": "Kavitha Sundaram",
    "ctr-003-C-01": "Lakshmi Bhat",
    "ctr-003-A-04": "Ritika Bansal",
    "ctr-003-D-02": "Naveen Prasad",
    "ctr-004-B-11": "Meera Krishnan",
    "ctr-004-C-04": "Aditya Menon",
    "ctr-004-A-15": "Karthik Rajan",
    "ctr-004-D-09": "Amit Saxena",
    "ctr-004-B-03": "Pooja Thakur",
    "ctr-004-A-06": "Rekha Mohan",
  };

  let seatIndex = 0;
  for (const config of centerConfigs) {
    for (let floor = 1; floor <= config.floors; floor++) {
      for (let s = 1; s <= config.seatsPerFloor; s++) {
        seatIndex++;
        const zone = zones[(s - 1) % 4];
        const num =
          Math.ceil(s / 4) +
          (floor - 1) * Math.ceil(config.seatsPerFloor / 4);
        const number = `${zone}-${String(num).padStart(2, "0")}`;
        const key = `${config.centerId}-${number}`;

        let type: "hot-desk" | "dedicated" | "cabin" | "meeting-room";
        if (s <= 2 && floor === config.floors) {
          type = "meeting-room";
        } else if (zone === "C" || zone === "D") {
          type = s % 3 === 0 ? "cabin" : "dedicated";
        } else {
          type = s % 2 === 0 ? "dedicated" : "hot-desk";
        }

        let status: "available" | "occupied" | "reserved" | "maintenance";
        let clientName: string | undefined;
        if (occupiedMap[key]) {
          status = "occupied";
          clientName = occupiedMap[key];
        } else if (seatIndex % 11 === 0) {
          status = "maintenance";
        } else if (seatIndex % 7 === 0) {
          status = "reserved";
        } else {
          status = "available";
        }

        allSeats.push({
          id: `seat-${String(seatIndex).padStart(3, "0")}`,
          number,
          floor,
          zone,
          type,
          status,
          clientName,
          centerId: config.centerId,
        });
      }
    }
  }

  return allSeats;
}

